-- 134 — El cambio de modo reinicia el ciclo activo, archiva y no borra
--
-- Tanda 3 de la corrección de base cero (odd/tasks/base-cero-logica.md, S3).
--
-- QUÉ ESTABA MAL
-- `fn_configurar_modo_presupuesto` reiniciaba las asignaciones con
--     WHERE mes_periodo = date_trunc('month', CURRENT_DATE)
-- que es el mes CALENDARIO, no el ciclo. Con `dia_ancla_ciclo > 1` y hoy antes del
-- ancla, el ciclo activo empezó el mes anterior: la función ponía en 0 el ciclo
-- siguiente (que el usuario todavía no vive) y dejaba intactas las asignaciones
-- del vigente. Hay usuarios con ancla 8, 10, 28 y 31.
--
-- Y en las dos direcciones el reset era `SET monto_limite = 0` a secas: volver a
-- anticipado borraba las asignaciones del ciclo sin aviso y sin dejar rastro.
--
-- QUÉ HACE AHORA
--   - Usa el ciclo activo: `fn_obtener_fechas_ciclo_presupuesto(CURRENT_DATE)` y
--     de ahí `date_trunc('month', fecha_inicio)`, que es la misma clave que
--     escribe la app (`fn_asignar_presupuesto`).
--   - Antes de poner en 0, archiva el valor anterior en
--     `p_presupuestos_historial` (append-only) con el motivo y los modos.
--   - No borra filas: `p_presupuestos` sigue igual, con el límite en 0.
--
-- La tabla de historial queda con RLS habilitado y sin policies: solo la escribe la
-- función SECURITY DEFINER. La app no la lee (todavía).

CREATE TABLE IF NOT EXISTS public.p_presupuestos_historial (
    historial_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    presupuesto_id bigint,
    estructura_egreso_id bigint,
    user_id bigint,
    hogar_id bigint,
    mes_periodo date NOT NULL,
    dia_ancla smallint,
    monto_limite numeric NOT NULL,
    motivo text NOT NULL,
    modo_origen text,
    modo_destino text,
    creado_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_p_presupuestos_historial_user_periodo
    ON public.p_presupuestos_historial (user_id, mes_periodo);

ALTER TABLE public.p_presupuestos_historial ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.p_presupuestos_historial IS
    'Ronda 7 (B3): copia de las asignaciones antes de que el cambio de modo de presupuesto las ponga en 0. Append-only.';

-- Archiva (sin borrar) las asignaciones no nulas de un ciclo. Idempotente por
-- diseño: si se llama dos veces, archiva dos veces el valor vigente, que es lo
-- que se quiere registrar.
CREATE OR REPLACE FUNCTION public.fn_archivar_presupuestos_ciclo(
    p_user_id bigint,
    p_mes_periodo date,
    p_motivo text,
    p_modo_origen text,
    p_modo_destino text
) RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
    v_filas integer := 0;
BEGIN
    INSERT INTO public.p_presupuestos_historial (
        presupuesto_id, estructura_egreso_id, user_id, hogar_id,
        mes_periodo, dia_ancla, monto_limite, motivo, modo_origen, modo_destino)
    SELECT p.presupuesto_id, p.estructura_egreso_id, p.user_id, p.hogar_id,
           p.mes_periodo, p.dia_ancla, p.monto_limite, p_motivo, p_modo_origen, p_modo_destino
    FROM public.p_presupuestos p
    WHERE p.user_id = p_user_id
      AND p.mes_periodo = p_mes_periodo
      AND p.monto_limite <> 0;
    GET DIAGNOSTICS v_filas = ROW_COUNT;
    RETURN v_filas;
END;
$function$;

CREATE OR REPLACE FUNCTION public.fn_configurar_modo_presupuesto(p_modo text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
    v_user_id bigint;
    v_modo_actual text;
    v_fecha_activacion date;
    v_inicio_ciclo_actual date;
    -- Clave de fila del ciclo ACTIVO (el que el usuario esta viviendo).
    v_mes_ciclo_actual date;
BEGIN
    SELECT user_id INTO v_user_id FROM public.usuarios WHERE auth_id = auth.uid();
    IF v_user_id IS NULL THEN RAISE EXCEPTION '{"key": "error_unauthorized", "params": {}}'; END IF;

    IF p_modo NOT IN ('base_cero', 'anticipado') THEN
        RAISE EXCEPTION '{"key": "error_budget_mode_invalid", "params": {}}';
    END IF;

    -- Agregar columna si no existe (por si acaso no fue añadida manualmente)
    BEGIN
        ALTER TABLE p_presupuestos_config ADD COLUMN IF NOT EXISTS fecha_activacion_base_cero date;
    EXCEPTION WHEN OTHERS THEN
        -- Ignorar si no hay permisos de DDL, asumimos que ya existe o se creará.
    END;

    SELECT modo_presupuesto, fecha_activacion_base_cero 
    INTO v_modo_actual, v_fecha_activacion
    FROM p_presupuestos_config WHERE user_id = v_user_id;

    SELECT fecha_inicio INTO v_inicio_ciclo_actual FROM public.fn_obtener_fechas_ciclo_presupuesto(CURRENT_DATE);
    -- B3/S3: p_presupuestos se indexa por el primer dia del mes del ciclo. Con
    -- dia_ancla > 1 y hoy antes del ancla, el ciclo activo empezo el mes ANTERIOR:
    -- date_trunc('month', CURRENT_DATE) apuntaba al ciclo siguiente y dejaba
    -- intactas las asignaciones del ciclo vigente.
    v_mes_ciclo_actual := date_trunc('month', v_inicio_ciclo_actual);

    IF v_modo_actual = 'base_cero' AND p_modo = 'anticipado' THEN
        -- Si cambió a base cero ESTE ciclo presupuestario, no puede volver a anticipado hasta el ciclo que viene
        IF v_fecha_activacion IS NOT NULL AND v_fecha_activacion >= v_inicio_ciclo_actual THEN
            RAISE EXCEPTION '{"key": "error_base_cero_locked", "params": {}}';
        END IF;
    END IF;

    IF p_modo = 'base_cero' AND COALESCE(v_modo_actual, '') != 'base_cero' THEN
        -- Reiniciar las asignaciones del ciclo ACTIVO (no del mes calendario).
        -- Antes de ponerlas en 0 se archivan: el reset es del modo, no un borrado.
        PERFORM public.fn_archivar_presupuestos_ciclo(v_user_id, v_mes_ciclo_actual, 'cambio_a_base_cero', v_modo_actual, p_modo);
        UPDATE p_presupuestos
        SET monto_limite = 0
        WHERE user_id = v_user_id AND mes_periodo = v_mes_ciclo_actual;

        INSERT INTO p_presupuestos_config (user_id, modo_presupuesto, fecha_activacion_base_cero)
        VALUES (v_user_id, p_modo, CURRENT_DATE)
        ON CONFLICT (user_id) 
        DO UPDATE SET modo_presupuesto = EXCLUDED.modo_presupuesto, fecha_activacion_base_cero = EXCLUDED.fecha_activacion_base_cero;
    ELSIF COALESCE(v_modo_actual, '') != p_modo THEN
        -- Lo mismo al volver a anticipado: se archiva y se reinicia el ciclo activo.
        PERFORM public.fn_archivar_presupuestos_ciclo(v_user_id, v_mes_ciclo_actual, 'vuelta_a_anticipado', v_modo_actual, p_modo);
        UPDATE p_presupuestos
        SET monto_limite = 0
        WHERE user_id = v_user_id AND mes_periodo = v_mes_ciclo_actual;

        INSERT INTO p_presupuestos_config (user_id, modo_presupuesto)
        VALUES (v_user_id, p_modo)
        ON CONFLICT (user_id) 
        DO UPDATE SET modo_presupuesto = EXCLUDED.modo_presupuesto;
    ELSE
        -- Solo actualizar (aunque sean iguales, por si acaso)
        INSERT INTO p_presupuestos_config (user_id, modo_presupuesto)
        VALUES (v_user_id, p_modo)
        ON CONFLICT (user_id) 
        DO UPDATE SET modo_presupuesto = EXCLUDED.modo_presupuesto;
    END IF;
END;
$function$
